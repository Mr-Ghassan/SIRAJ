/* ------------------------------------------------------------ helpers -- */
function url(src, params) {
  const qs = new URLSearchParams(params).toString();
  return 'file://' + P(src) + (qs ? '?' + qs : '');
}
async function openUrl(u, { width = 1400, height = 1000, scale = 1 } = {}) {
  const b = await R.browser();
  const page = await b.newPage({ viewport: { width, height }, deviceScaleFactor: scale });
  page.on('console', (m) => { if (m.type() === 'warning' || m.type() === 'error') console.warn('   ', m.text()); });
  page.on('pageerror', (e) => console.error('   page error:', e.message));
  await page.goto(u, { waitUntil: 'load' });
  await page.evaluate(async () => { if (window.SIRAJ) await window.SIRAJ.ready; await document.fonts.ready; });
  await page.waitForTimeout(120);
  return page;
}
function fixPdfDates(file) {
  const buf = fs.readFileSync(file);
  const s = buf.toString('latin1').replace(/\/(CreationDate|ModDate) \(D:(\d{14})/g, (m, k) => `/${k} (D:${FIXED_DATE}`);
  fs.writeFileSync(file, Buffer.from(s, 'latin1'));
}
const outFile = (job, type, ext) => P(job.dir.replace('{T}', type), `SIRAJ_${job.name}_${V}.${ext}`);

async function renderPdf(job) {
  const params = { name: `SIRAJ_${job.name}_${V}` };
  if (job.marks) params.marks = '1';
  if (job.dieline === false) params.dieline = '0';
  const page = await openUrl(url(job.src, params));
  const out = outFile(job, 'PDF', 'pdf');
  R.ensureDir(out);
  if (job.flow) {
    await page.pdf({ path: out, printBackground: true, preferCSSPageSize: true });
  } else {
    const ps = await page.evaluate(() => window.SIRAJ.pageSize());
    await page.pdf({ path: out, width: ps.width, height: ps.height, printBackground: true, preferCSSPageSize: false, margin: { top: 0, right: 0, bottom: 0, left: 0 } });
  }
  await page.close();
  fixPdfDates(out);
  return out;
}

async function renderPng(job) {
  const params = { preview: '1', name: `SIRAJ_${job.name}_${V}` };
  if (job.marks) params.marks = '1';
  if (job.dieline === false) params.dieline = '0';
  const out = outFile(job, 'PNG', 'png');
  R.ensureDir(out);
  if (job.flow) {
    // flowing documents: rasterise the PDF pages side by side via the preview stage of the PDF itself
    return renderFlowPng(job, out);
  }
  // measure at scale 1, then shoot at the target scale
  let page = await openUrl(url(job.src, params));
  const box = await page.evaluate(() => { const s = document.querySelector('.pv-stage'); const r = s.getBoundingClientRect(); return { w: Math.ceil(r.width), h: Math.ceil(r.height) }; });
  await page.close();
  page = await openUrl(url(job.src, params), { width: box.w, height: box.h, scale: job.scale || 1.5 });
  await page.screenshot({ path: out, clip: { x: 0, y: 0, width: box.w, height: box.h } });
  await page.close();
  return out;
}

// Flow documents paginate in the print engine only; preview = PDF pages rasterised with pdftoppm when available.
async function renderFlowPng(job, out) {
  const { execFileSync } = require('child_process');
  const pdfFile = outFile(job, 'PDF', 'pdf');
  const tmp = path.join(ROOT, 'tools', '.cache', `flow-${job.name}`);
  fs.mkdirSync(tmp, { recursive: true });
  execFileSync('pdftoppm', ['-png', '-r', String(Math.round(96 * (job.scale || 1.2))), pdfFile, path.join(tmp, 'p')]);
  const pages = fs.readdirSync(tmp).filter((f) => f.endsWith('.png')).sort();
  const imgs = pages.map((f) => `<figure class="pv-fig"><img src="${path.join(tmp, f)}" style="width:210mm;height:297mm;box-shadow:0 .3mm .6mm rgba(23,6,8,.1),0 6mm 14mm -6mm rgba(23,6,8,.32)"><figcaption>Page ${pages.indexOf(f) + 1} · auto-paginated</figcaption></figure>`).join('');
  const html = `<!doctype html><html class="is-preview"><head><meta charset="utf-8"><link rel="stylesheet" href="file://${P('19-Templates/docs/css/siraj-doc.css')}"></head><body><div class="pv-stage"><header class="pv-head"><p class="pv-eyebrow"><span class="pv-lumen"></span>SIRAJ · Document Kit</p><h1 class="pv-title">Flow template — auto-paginated A4 with running footer &amp; page numbers</h1></header><div class="pv-grid" style="--pv-cols:${Math.min(pages.length, 3)}">${imgs}</div></div></body></html>`;
  const f = R.tmpHtml(html, 'flowpv');
  let page = await openUrl('file://' + f);
  const box = await page.evaluate(() => { const r = document.querySelector('.pv-stage').getBoundingClientRect(); return { w: Math.ceil(r.width), h: Math.ceil(r.height) }; });
  await page.close();
  page = await openUrl('file://' + f, { width: box.w, height: box.h, scale: 1 });
  await page.screenshot({ path: out, clip: { x: 0, y: 0, width: box.w, height: box.h } });
  await page.close();
  fs.rmSync(f, { force: true });
  fs.rmSync(tmp, { recursive: true, force: true });
  return out;
}

/* ---------------------------------------------------- email signature -- */
function emailSignatures(cfg) {
  const sig = require('../19-Templates/email-signature/signature.template.js');
  const dir = P('19-Templates/email-signature');
  const files = [];
  for (const lang of ['EN', 'AR']) {
    const html = sig.render(cfg, lang, { logoUrl: cfg.print.email.logo_url });
    const f = path.join(dir, `SIRAJ_Email-Signature_${lang}_${V}.html`);
    fs.writeFileSync(f, html);
    files.push({ lang, file: f });
  }
  return files;
}
