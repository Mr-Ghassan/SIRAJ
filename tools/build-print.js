/* --------------------------------------------------------------- main -- */
(async () => {
  const filters = process.argv.slice(2).map((s) => s.toLowerCase());
  const cfg = loadConfig();
  writeConfigJs(cfg);
  const sigs = emailSignatures(cfg);
  const jobs = JOBS.filter((j) => !filters.length || filters.some((f) => (j.name + ' ' + j.src).toLowerCase().includes(f)));
  let n = 0;
  for (const job of jobs) {
    if (!fs.existsSync(P(job.src))) { console.warn('skip (missing):', job.src); continue; }
    const pdf = await renderPdf(job);
    const png = await renderPng(job);
    n++;
    console.log('✓', path.relative(ROOT, pdf), '·', path.relative(ROOT, png));
  }
  if (!filters.length || filters.some((f) => 'email signature'.includes(f))) {
    const pv = await emailPreviews(cfg);
    console.log('✓', sigs.map((s) => path.relative(ROOT, s.file)).join(' · '), '·', path.relative(ROOT, pv));
  }
  await R.close();
  console.log(`print: ${n} jobs rendered`);
})().catch(async (e) => { console.error(e); await R.close(); process.exit(1); });
