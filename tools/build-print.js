// SIRAJ Print & Corporate Collateral — deterministic build.
//
//   node tools/build-print.js            build everything
//   node tools/build-print.js card memo  build only jobs whose name contains a filter
//
// 1. Generates 19-Templates/docs/js/brand-config.js from 00-Brand-Foundation/brand.config.json
//    (+ 12-Print/Source/print.config.json for print-only placeholders such as VATIN / bank).
// 2. Generates the email signatures (19-Templates/email-signature/) from the same config.
// 3. Renders every HTML template to PDF (vector text, exact page size) and a PNG preview.
//    PDFs get fixed CreationDate/ModDate so identical sources give identical bytes.
const fs = require('fs');
const path = require('path');
const R = require('./lib/render');

const ROOT = R.ROOT;
const V = 'v1.0';
const P = (...a) => path.join(ROOT, ...a);
const FIXED_DATE = '20261001000000'; // 14 digits — same length as Chromium's timestamp

/* ------------------------------------------------------------- config -- */
function loadConfig() {
  const brand = JSON.parse(fs.readFileSync(P('00-Brand-Foundation/brand.config.json'), 'utf8'));
  const print = JSON.parse(fs.readFileSync(P('12-Print/Source/print.config.json'), 'utf8'));
  return { ...brand, print };
}
function writeConfigJs(cfg) {
  const out = P('19-Templates/docs/js/brand-config.js');
  fs.writeFileSync(out, `/* GENERATED by tools/build-print.js from 00-Brand-Foundation/brand.config.json\n   and 12-Print/Source/print.config.json. Do not edit — edit the JSON and rebuild. */\nwindow.SIRAJ_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
  return out;
}

