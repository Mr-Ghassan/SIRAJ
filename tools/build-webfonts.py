#!/usr/bin/env python3
"""SIRAJ Brand Library v1.0.1 — WOFF2 web exports of the official brand fonts (lossless, no subsetting).

Source: 03-Typography/fonts/<Family>/*.ttf (the licensed OFL masters). Output:
  03-Typography/fonts/WOFF2/<Family>/<Name>.woff2   (same glyphs, tables and metrics; WOFF2 = compressed container)
  03-Typography/siraj-fonts-woff2.css                (the @font-face set of siraj-fonts.css, WOFF2 first, TTF fallback)
Every output is checked: same glyph order, same cmap, same family/style names as its TTF.
Usage: python3 -I tools/build-webfonts.py      (needs fontTools + brotli)
"""
import pathlib, re, shutil, sys
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / '03-Typography' / 'fonts'
OUT = FONTS / 'WOFF2'
errors, written = [], 0
for ttf in sorted(FONTS.glob('*/*.ttf')):
    family = ttf.parent.name
    dst = OUT / family / (ttf.stem + '.woff2')
    dst.parent.mkdir(parents=True, exist_ok=True)
    f = TTFont(ttf)
    f.flavor = 'woff2'
    f.save(dst)
    a, b = TTFont(ttf), TTFont(dst)
    if a.getGlyphOrder() != b.getGlyphOrder() or a['cmap'].getBestCmap() != b['cmap'].getBestCmap() \
            or a['name'].getDebugName(4) != b['name'].getDebugName(4):
        errors.append(str(dst))
    written += 1

for fam in OUT.iterdir():  # every web copy travels with its licence
    shutil.copyfile(FONTS / fam.name / 'OFL.txt', fam / 'OFL.txt')

css = (ROOT / '03-Typography' / 'siraj-fonts.css').read_text(encoding='utf-8')
css = re.sub(r'src: url\("fonts/(\w+)/([\w-]+)\.ttf"\) format\("truetype"\);',
             r'src: url("fonts/WOFF2/\1/\2.woff2") format("woff2"), url("fonts/\1/\2.ttf") format("truetype");', css)
css = css.replace('/* SIRAJ brand fonts', '/* SIRAJ brand fonts (web: WOFF2 first, TTF fallback; generated by tools/build-webfonts.py)', 1)
(ROOT / '03-Typography' / 'siraj-fonts-woff2.css').write_text(css, encoding='utf-8')
print(f'webfonts: {written} WOFF2 files · mismatches: {len(errors)}')
for e in errors:
    print('MISMATCH', e)
sys.exit(1 if errors else 0)
