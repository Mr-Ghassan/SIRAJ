// SIRAJ content generator: one short JSON brief → finished, on-brand social posts (Arabic by default).
//
//   node tools/make-post.js 11-Social/Content/briefs/siraj-teaser.json
//   node tools/make-post.js brief.json --formats post,story,square
//
// The brief uses the same fields as the templates in 11-Social/Templates (layout, env, photo, still,
// overlay, blocks …), so every post goes through the one SIRAJ template engine (social.js): grid, Tajawal,
// Western digits, logo rules, real-silk stills and the layout QA are applied automatically.
// Output: 11-Social/Content/<date>_<name>/<name>_<Format>_AR.png + source.html (re-open to tweak) + brief.json.
//
// Brief fields (all optional except name and ar.title):
//   name        "Siraj-Teaser-01"                        file-safe name
//   formats     ["post","story"]                         post 1080×1350 · square · story/reel 1080×1920 · li · x
//   layout      "type" | "hero" | "window" | "split"     type = text on a field; hero = full-bleed photo;
//                                                          window/split = photo in a SIRAJ window / half frame
//   env         "ivory" | "linen" | "deep" | "shadow" | "maroon" | "photo"
//   photo       library name (Residential-Tower-Golden-Hour) or repo path (14-Property-Marketing/…/x.jpg)
//   pos         CSS object-position for the photo ("50% 30%")
//   still       real-silk background formation (Drape-Deep, Drape-Lumen, Ribbon-Sweep, Horizon-Deep, …)
//   overlay     "horizon" (real silk ground line over a photo) | "scrim" (dark fall for legibility)
//   display     true → large display title
//   ar          { eyebrow, title, lead, blocks:[{type:"facts"|"stats"|"list"|"details"|"quote"|"progress", …}], end }
//               a quote post needs no title: { "blocks": [{ "type": "quote", "text": "…", "cite": "…" }] }
//   formats_ar  per-format copy overrides, e.g. { "story": { "lead": "…" } }
//   per_format  per-format design overrides, e.g. { "story": { "photo": "…_9x16_v1.0.jpg", "pos": "50% 40%" } }
// Text tokens resolve from 00-Brand-Foundation/brand.config.json: {contact.website} {contact.social_handle}
// {founding_project.name_ar} …  Wrap Latin runs that must stay LTR in [[ ]], e.g. [[sirajproperties.net]].
const fs = require('fs');
const path = require('path');
const R = require('./lib/render');

const SIZE = { post: [1080, 1350], square: [1080, 1080], story: [1080, 1920], reel: [1080, 1920], carousel: [1080, 1350], li: [1200, 627], x: [1600, 900] };
const FNAME = { post: 'Post', square: 'Square', story: 'Story', reel: 'Reel', carousel: 'Carousel', li: 'LinkedIn', x: 'X' };

(async () => {
  const args = process.argv.slice(2);
  if (!args[0]) { console.error('usage: node tools/make-post.js <brief.json> [--formats post,story]'); process.exit(1); }
  const brief = JSON.parse(fs.readFileSync(args[0], 'utf8'));
  const fi = args.indexOf('--formats');
  const formats = fi >= 0 ? args[fi + 1].split(',') : brief.formats || ['post', 'story'];
  const lang = brief.lang || 'ar';                                    // SIRAJ communicates in Arabic (language policy)
  const copy = brief[lang] || {};
  if (!brief.name || !(copy.title || (copy.blocks && copy.blocks.length))) throw new Error(`brief needs "name" and "${lang}.title" (or "${lang}.blocks", e.g. a quote)`);
  const bad = formats.filter((f) => !SIZE[f]);
  if (bad.length) throw new Error('unknown format(s): ' + bad.join(', '));

  const day = new Date().toISOString().slice(0, 10);
  const dir = path.join(R.ROOT, '11-Social', 'Content', `${brief.date || day}_${brief.name}`);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'brief.json'), JSON.stringify(brief, null, 2) + '\n');

  // the data block the template engine expects
  const data = { ...brief, exports: Object.fromEntries(formats.map((f) => [f, [lang]])) };
  delete data.formats; delete data.formats_ar; delete data.per_format; // "formats" means per-format overrides to the engine
  data.formats = {};
  // per_format: design overrides per format (e.g. the native 9:16 photo for stories); formats_ar: copy overrides
  for (const [f, o] of Object.entries(brief.per_format || {})) data.formats[f] = { ...(data.formats[f] || {}), ...o };
  for (const [f, o] of Object.entries(brief.formats_ar || {})) data.formats[f] = { ...(data.formats[f] || {}), [lang]: o };
  // window / split layouts need a media frame: default to half the canvas (a little less on tall formats)
  if ((data.layout === 'window' || data.layout === 'split') && !data.media) {
    data.media = { h: 0.5 };
    for (const f of ['story', 'reel']) data.formats[f] = { media: { h: 0.42 }, ...(data.formats[f] || {}) };
  }
  const html = `<!doctype html>
<html><head><meta charset="utf-8"><title>SIRAJ · ${brief.name}</title>
<!-- Generated by tools/make-post.js from brief.json — edit the brief and re-run rather than this file. -->
<link rel="stylesheet" href="../../../09-Design-System/css/siraj.css">
<link rel="stylesheet" href="../../Templates/social.css">
<script>window.SIRAJ_ROOT = '../../../';</script>
<script id="data" type="application/json">${JSON.stringify(data, null, 2)}</script>
</head><body><script src="../../Templates/brand-data.js"></script><script src="../../Templates/social.js"></script></body></html>
`;
  const src = path.join(dir, 'source.html');
  fs.writeFileSync(src, html);

  const problems = [];
  for (const f of formats) {
    const [w, h] = SIZE[f];
    const { page, cleanup } = await R.openPage({ file: `${src}?format=${f}&lang=${lang}`, width: w, height: h });
    await page.waitForSelector('body[data-ready="1"]', { timeout: 30000 });
    const qa = await page.evaluate(() => window.__qa || []);
    const out = path.join(dir, `SIRAJ_${brief.name}_${FNAME[f]}_${lang.toUpperCase()}_v1.0.png`);
    await page.screenshot({ path: out, clip: { x: 0, y: 0, width: w, height: h } });
    await cleanup();
    console.log(`  ${qa.length ? '!' : '✓'} ${path.relative(R.ROOT, out)}`);
    qa.forEach((m) => problems.push(`${FNAME[f]}: ${m}`));
  }
  await R.close();
  if (problems.length) { console.log('\nLayout QA:\n  - ' + problems.join('\n  - ')); process.exitCode = 2; }
  else console.log('\nAll formats passed layout QA.');
})().catch((e) => { console.error(e.message || e); process.exit(1); });
