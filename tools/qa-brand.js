// SIRAJ Brand QA v1.0 — scans every PUBLIC source and generated text file for content that breaks the brand rules.
// Usage: node tools/qa-brand.js            → prints a report and writes docs/qa/BRAND_QA_REPORT.md; exit 1 on failures
// Scope: public deliverables only. Archives (99-Archive), internal strategy docs, rule books (AGENTS.md, skill, prompt
// rule sections) and node_modules are excluded because they *name* the forbidden terms on purpose.
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const PUBLIC = [
  '01-Logos', '02-Colours', '03-Typography', '04-Grids', '05-Graphic-System', '06-SIRAJ-Silk', '07-Icon-System',
  '11-Social/Briefs', '11-Social/Templates', '12-Print/Source', '13-Presentations', '14-Property-Marketing/12-Project-Siraj',
  '15-Motion-System/components', '15-Motion-System/transitions', '16-Intro/source', '17-Outro/source', '19-Templates',
  '20-Brand-Guidelines/source', 'design-system', 'motion-system',
];
const EXT = /\.(html|js|json|css|svg|md|txt|ts)$/i;
const SKIP = /node_modules|99-Archive|QA_REPORT|\/qa\/|brand-data\.js$|siraj-brand-data\.js$|brand-config\.js$|README\.md$|STATUS\.md$|design-system\/docs\/usage\.html$/;

// [label, regex, severity]
const RULES = [
  ['fictional project «مساكن نور» / Noor', /مساكن نور|Noor Residences|\bNoor\b|noor\./, 'fail'],
  ['fictional project «حرير» / Harir', /«حرير»|مشروع حرير|\bHarir\b|harir\./, 'fail'],
  ['website not written WWW.SIRAJPROPERTIES.NET', /(?<!https:\/\/www\.)sirajproperties\.net|(?<!https:\/\/)www\.sirajproperties\.net|(?<!WWW\.)SIRAJPROPERTIES\.NET|SirajProperties\.|Sirajproperties\./, 'fail'],
  ['«@» before the handle (use the Instagram icon)', /@SIRAJPROPERTIES|@sirajproperties/, 'fail'],
  ['phone not grouped «7771 4404»', /(?<!tel:)(?<!968)(?<!wa\.me\/)(?<!"phone":\s?")(?<!phone: ')77714404/, 'fail'],
  ['email on public material', /\b[\w.]+@[\w-]+\.(com|net|om)\b|example\.com/, 'fail'],
  ['old / placeholder phone', /2400 0000|9000 0000|9100 0000|9200 0000|\[رقم الهاتف\]|phone_post_placeholder/, 'fail'],
  ['placeholder text', /\bPLACEHOLDER\b|Lorem ipsum|\[PLACEHOLDER|\[البنك|TODO:/, 'fail'],
  ['internal label «المشروع المؤسِّس» / Founding Project', /المشروع المؤسِّس|المشروع المؤسس|Founding Project/, 'fail'],
  ['internal strategy line', /لا تبدأ بالانتشار|بل تبدأ بمعيار|إثبات ← توسّع|PROVE → EXPAND/, 'fail'],
  ['floor wording (use «شقق سكنية ومحلات تجارية»)', /في الأعلى|في الأرض|الطابق الأرضي/, 'fail'],
  ['wrong terminology', /سكنٌ ومتاجر|شقق ومتاجر|مساكن ومتاجر/, 'fail'],
  ['fictional person', /Al Rawahi|الرواحي|Al Balushi|البلوشي|Al Lawati|اللواتي/, 'fail'],
  ['self-praising "standard" copy', /يبدأ المعيار|يضع المعيار|يؤسس معيار|بمعيارٍ كامل/, 'fail'],
];

const files = [];
(function walk(dir) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return;
  for (const f of fs.readdirSync(abs)) {
    const rel = path.join(dir, f);
    if (SKIP.test(rel)) continue;
    const st = fs.statSync(path.join(ROOT, rel));
    if (st.isDirectory()) walk(rel); else if (EXT.test(f) && st.size < 3e6) files.push(rel);
  }
})('.');
const inScope = files.filter((f) => PUBLIC.some((p) => f.startsWith(p + '/') || f === p));

const hits = [];
for (const f of inScope) {
  const lines = fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n');
  lines.forEach((ln, i) => {
    for (const [label, re, sev] of RULES) if (re.test(ln)) hits.push({ f, line: i + 1, label, sev, text: ln.trim().slice(0, 140) });
  });
}
// file-name checks for public exports (images / video / pdf)
const BIN = /\.(png|jpe?g|webp|mp4|webm|mov|pdf|pptx)$/i;
const binFiles = [];
(function walkBin(dir) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return;
  for (const f of fs.readdirSync(abs)) {
    const rel = path.join(dir, f);
    if (/node_modules|99-Archive|\.git/.test(rel)) continue;
    const st = fs.statSync(path.join(ROOT, rel));
    if (st.isDirectory()) walkBin(rel); else if (BIN.test(f)) binFiles.push(rel);
  }
})('.');
for (const f of binFiles) if (/Noor|Harir|Outro_Url|Outro_Cta|Outro_Contact|Outro_Social|Bilingual-Lockup/.test(f) || (/1[6-7]-(Intro|Outro)\//.test(f) && /_1x1_/.test(f))) hits.push({ f, line: 0, label: 'demo / retired asset still public', sev: 'fail', text: path.basename(f) });

const fails = hits.filter((h) => h.sev === 'fail');
const byLabel = {};
for (const h of hits) (byLabel[h.label] = byLabel[h.label] || []).push(h);
let md = `# SIRAJ Brand QA report\n\nGenerated by \`node tools/qa-brand.js\` on ${new Date().toISOString().slice(0, 10)}.\n\n`;
md += `- Public text files scanned: **${inScope.length}**\n- Public binary files checked by name: **${binFiles.length}**\n- Rules: **${RULES.length + 1}**\n- Failures: **${fails.length}**\n\n`;
md += fails.length ? '## Failures\n\n' + Object.entries(byLabel).map(([l, hs]) => `### ${l} (${hs.length})\n` + hs.slice(0, 40).map((h) => `- \`${h.f}:${h.line}\` — ${h.text.replace(/`/g, "'")}`).join('\n')).join('\n\n') + '\n' : '## Result\n\nNo violations found in public material. ✅\n';
md += '\n## Rules checked\n\n' + RULES.map(([l]) => `- ${l}`).join('\n') + '\n- demo / retired asset file names\n';
fs.mkdirSync(path.join(ROOT, 'docs', 'qa'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'qa', 'BRAND_QA_REPORT.md'), md);
console.log(`scanned ${inScope.length} text + ${binFiles.length} binary files · failures: ${fails.length}`);
for (const [l, hs] of Object.entries(byLabel)) { console.log(`  ✗ ${l}: ${hs.length}`); hs.slice(0, 6).forEach((h) => console.log(`      ${h.f}:${h.line}  ${h.text.slice(0, 90)}`)); }
process.exitCode = fails.length ? 1 : 0;
