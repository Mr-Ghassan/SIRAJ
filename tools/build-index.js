// Generate ASSET-INDEX.md — a complete, grouped inventory of every brand asset in the repository.
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const SKIP = new Set(['node_modules', '.git', '.cache', '_build']);
const human = (n) => (n > 1048576 ? (n / 1048576).toFixed(1) + ' MB' : n > 1024 ? (n / 1024).toFixed(0) + ' KB' : n + ' B');
const top = fs.readdirSync(ROOT).filter((d) => /^\d\d-/.test(d) && fs.statSync(path.join(ROOT, d)).isDirectory()).sort();
let total = 0, count = 0;
let md = `# SIRAJ Brand Identity v1.0 — Asset Index\n\nGenerated by \`npm run build:index\` on ${new Date().toISOString().slice(0, 10)}. Paths are relative to the repository root.\n\n`;
const summary = [];
const sections = [];
for (const d of top) {
  const files = [];
  (function walk(dir) {
    for (const f of fs.readdirSync(dir).sort()) {
      if (SKIP.has(f) || f.startsWith('.')) continue;
      const p = path.join(dir, f); const s = fs.statSync(p);
      if (s.isDirectory()) walk(p); else files.push([path.relative(ROOT, p).split(path.sep).join('/'), s.size]);
    }
  })(path.join(ROOT, d));
  const size = files.reduce((a, [, s]) => a + s, 0);
  total += size; count += files.length;
  const byExt = {};
  files.forEach(([f]) => { const e = path.extname(f).slice(1).toLowerCase() || '—'; byExt[e] = (byExt[e] || 0) + 1; });
  summary.push(`| [${d}](#${d.toLowerCase()}) | ${files.length} | ${human(size)} | ${Object.entries(byExt).sort((a, b) => b[1] - a[1]).map(([e, n]) => `${e} ×${n}`).join(', ')} |`);
  // group by sub-folder
  const groups = {};
  files.forEach(([f, s]) => { const g = path.dirname(f); (groups[g] = groups[g] || []).push([path.basename(f), s]); });
  let sec = `\n## ${d}\n\n`;
  const readme = path.join(ROOT, d, 'README.md');
  if (fs.existsSync(readme)) sec += `Specification: [\`${d}/README.md\`](${d}/README.md)\n\n`;
  for (const [g, list] of Object.entries(groups)) {
    sec += `<details><summary><b>${g}/</b> — ${list.length} file${list.length > 1 ? 's' : ''}</summary>\n\n| File | Size |\n|---|---|\n${list.map(([f, s]) => `| [${f}](${encodeURI(g + '/' + f)}) | ${human(s)} |`).join('\n')}\n\n</details>\n\n`;
  }
  sections.push(sec);
}
md += `**${count} files · ${human(total)}**\n\n| Folder | Files | Size | Types |\n|---|---|---|---|\n${summary.join('\n')}\n` + sections.join('');
md += `\n## tools/\n\nBuild scripts. Every deliverable above is reproducible from source; see the README for commands.\n`;
fs.writeFileSync(path.join(ROOT, 'ASSET-INDEX.md'), md);
console.log('asset index:', count, 'files,', human(total));
