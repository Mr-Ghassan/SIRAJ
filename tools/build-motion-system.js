#!/usr/bin/env node
// SIRAJ Motion System v1.0 — build the motion tokens, the public data module and the measured footage track.
//
//   node tools/build-motion-system.js            (run after tools/build-motion-data.js)
//
// Inputs   motion-system/tokens/siraj-motion-levels.json  (the six levels — THE source, never changed here)
//          motion-system/tokens/src/siraj-motion.spec.json (principles, transitions, component timelines …)
//          00-Brand-Foundation/brand.config.json            (public contact + project name)
//          06-SIRAJ-Silk/Footage/*_alpha.webm               (real silk footage → measured track)
// Outputs  motion-system/tokens/siraj-motion.tokens.json   Motion Tokens v1.0 (full)
//          motion-system/tokens/build/siraj-motion.css     custom properties + .m-micro … .m-cinematic + reduced motion
//          motion-system/tokens/build/siraj-motion.ts      typed export
//          motion-system/tokens/build/siraj-motion.js      UMD (window.SIRAJ_MOTION_TOKENS) — also copied to 15-Motion-System/lib/
//          15-Motion-System/lib/siraj-public-data.js       ONLY the public fields (phone, handle, project name, city)
//          15-Motion-System/lib/siraj-footage-track.js     per-frame position of the real ribbon along the frame diagonal
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const P = (...a) => path.join(ROOT, ...a);
const LV = JSON.parse(fs.readFileSync(P('motion-system/tokens/siraj-motion-levels.json'), 'utf8'));
const SP = JSON.parse(fs.readFileSync(P('motion-system/tokens/src/siraj-motion.spec.json'), 'utf8'));
const CFG = JSON.parse(fs.readFileSync(P('00-Brand-Foundation/brand.config.json'), 'utf8'));
const WIND = JSON.parse(fs.readFileSync(P('motion-system/tokens/siraj-wind.json'), 'utf8'));   // AIR / WIND (client rule 2026-10-13)
// normalised wind levels for the Silk Motion Engine (strength 0..1, frequency band, foliage sway degrees = band midpoint)
const windEngine = Object.fromEntries(Object.entries(WIND.levels).map(([k, l], i, all) => [k, { v: +[0.08, 0.3, 0.6, 1][i].toFixed(2), f: l.silk_frequency_hz, deg: +((l.foliage_sway_deg[0] + l.foliage_sway_deg[1]) / 2).toFixed(2) }]));
const wind = { ...WIND, engine: windEngine };
const ORDER = ['micro', 'fast', 'standard', 'emphasis', 'hero', 'cinematic'];
const ms = (s) => parseFloat(String(s));
const css = (b) => `cubic-bezier(${b.join(', ')})`;

// ---------------------------------------------------------------- tokens
const easing = {};
for (const [k, v] of Object.entries({ ...LV.easing, ...SP.easingExtra })) easing[k] = { bezier: v.bezier, css: css(v.bezier), use: v.use };

const level = {};
ORDER.forEach((name, i) => {
  const L = LV.level[name], X = SP.levelExtra[name];
  if (!L) throw new Error('level missing in siraj-motion-levels.json: ' + name);
  level[name] = {
    order: i + 1,
    name_ar: X.ar,
    duration: { ms: ms(L.duration), s: ms(L.duration) / 1000 },
    ease: { name: L.ease, bezier: LV.easing[L.ease].bezier, css: css(LV.easing[L.ease].bezier) },
    stagger: { ms: ms(L.stagger), s: ms(L.stagger) / 1000 },
    scale: { from: L.scale[0], to: L.scale[1] },
    opacity: { from: L.opacity[0], to: L.opacity[1] },
    translate: { px: ms(L.translate) },
    blur: { px: ms(L.blur) },
    camera: L.camera,
    exit: { ms: X.exit, s: X.exit / 1000, ease: { name: 'release', bezier: easing.release.bezier, css: easing.release.css } },
    principle: X.principle,
    use: L.use,
  };
});
// the source values must survive untouched
for (const n of ORDER) {
  const L = LV.level[n], T = level[n];
  const same = T.duration.ms === ms(L.duration) && T.ease.name === L.ease && T.stagger.ms === ms(L.stagger) && T.scale.from === L.scale[0] && T.scale.to === L.scale[1]
    && T.translate.px === ms(L.translate) && T.blur.px === ms(L.blur) && T.camera === L.camera;
  if (!same) throw new Error('token drift on level ' + n);
}
// component timelines: resolve the level of every step to concrete seconds (docs + compositions read these)
const components = {};
for (const [k, c] of Object.entries(SP.components)) {
  components[k] = { ...c, timeline: c.timeline.map((s) => ({ ...s, dur: s.span ?? level[s.level].duration.s, ease: level[s.level].ease.name, stagger: level[s.level].stagger.s })) };
  if (c.out) components[k].out = { ...c.out, dur: level[c.out.level].exit.s, ease: 'release' };
}
const tokens = {
  $description: 'SIRAJ Motion Tokens v1.0 — GENERATED by tools/build-motion-system.js from siraj-motion-levels.json + src/siraj-motion.spec.json. Do not edit by hand.',
  $version: '1.0.0',
  order: ORDER,
  easing,
  level,
  principles: SP.principles,
  settle: SP.settle,
  camera: SP.camera,
  silk: SP.silk,
  wind,
  transitions: Object.fromEntries(Object.entries(SP.transitions).map(([k, t]) => [k, { ...t, ease_css: easing[t.ease].css }])),
  components,
  reducedMotion: SP.reducedMotion,
  forbidden: SP.forbidden,
  legacy: LV.note,
};
const OUTT = P('motion-system/tokens');
fs.mkdirSync(path.join(OUTT, 'build'), { recursive: true });
fs.writeFileSync(path.join(OUTT, 'siraj-motion.tokens.json'), JSON.stringify(tokens, null, 2) + '\n');

// ---------------------------------------------------------------- CSS
const head = '/* SIRAJ Motion Tokens v1.0 — GENERATED by tools/build-motion-system.js. Do not edit.\n   Levels: micro < fast < standard < emphasis < hero < cinematic. Principles: FLOW · DRAPE · REVEAL · WRAP · FOLD · GLIDE · SETTLE.\n   Usage:  <div class="m-emphasis m-enter" style="--m-i:2">…</div>  then add .is-in (e.g. via 15-Motion-System/web/siraj-motion-web.js).\n           .m-<level>.m-animate plays the entrance as a keyframe animation on load. */\n';
let C = head + ':root {\n';
for (const [k, e] of Object.entries(easing)) C += `  --siraj-ease-${k}: ${e.css};\n`;
C += `  --siraj-wind-direction: ${WIND.direction.deg}deg; /* right → left */\n`;
for (const [k, l] of Object.entries(windEngine)) C += `  --siraj-wind-${k}-strength: ${l.v}; --siraj-wind-${k}-hz: ${((l.f[0] + l.f[1]) / 2).toFixed(3)}; --siraj-wind-${k}-sway: ${l.deg}deg;\n`;
for (const n of ORDER) {
  const l = level[n];
  C += `  --siraj-m-${n}-duration: ${l.duration.ms}ms;\n  --siraj-m-${n}-ease: var(--siraj-ease-${l.ease.name});\n  --siraj-m-${n}-stagger: ${l.stagger.ms}ms;\n  --siraj-m-${n}-scale: ${l.scale.from};\n  --siraj-m-${n}-translate: ${l.translate.px}px;\n  --siraj-m-${n}-blur: ${l.blur.px}px;\n  --siraj-m-${n}-exit: ${l.exit.ms}ms;\n`;
}
C += '}\n\n';
for (const n of ORDER) C += `.m-${n} { --m-duration: var(--siraj-m-${n}-duration); --m-ease: var(--siraj-m-${n}-ease); --m-stagger: var(--siraj-m-${n}-stagger); --m-scale: var(--siraj-m-${n}-scale); --m-translate: var(--siraj-m-${n}-translate); --m-blur: var(--siraj-m-${n}-blur); --m-exit: var(--siraj-m-${n}-exit);\n  transition-property: opacity, transform, filter, clip-path; transition-duration: var(--m-duration); transition-timing-function: var(--m-ease); transition-delay: calc(var(--m-i, 0) * var(--m-stagger)); }\n`;
const ALL = ORDER.map((n) => '.m-' + n).join(', ');
C += `
/* SETTLE entrance: from translate/scale/blur/opacity of the level to rest */
.m-enter { opacity: 0; transform: translate3d(0, var(--m-translate, 16px), 0) scale(var(--m-scale, 1)); filter: blur(var(--m-blur, 0px)); }
.m-enter.is-in, .is-in > .m-enter { opacity: 1; transform: none; filter: none; }
/* REVEAL: content uncovered by a mask from the start side (inline-start = right in Arabic) */
.m-reveal { clip-path: inset(0 0 0 100%); }
[dir="rtl"] .m-reveal, .m-reveal:dir(rtl) { clip-path: inset(0 100% 0 0); }
.m-reveal.is-in { clip-path: inset(0 0 0 0); }
/* line rise: <span class="m-line"><span>…</span></span> */
.m-line { display: block; overflow: hidden; padding-block: .12em; }
.m-line > span { display: inline-block; transform: translateY(105%); transition: inherit; transition-property: transform; }
.m-line.is-in > span, .is-in .m-line > span { transform: none; }
/* exits leave calmly with the release curve and the level's exit duration */
.m-exit { transition-duration: var(--m-exit); transition-timing-function: var(--siraj-ease-release); opacity: 0; transform: translate3d(0, calc(var(--m-translate, 16px) * -.5), 0); }

@keyframes siraj-m-enter { from { opacity: 0; transform: translate3d(0, var(--m-translate, 16px), 0) scale(var(--m-scale, 1)); filter: blur(var(--m-blur, 0px)); } to { opacity: 1; transform: none; filter: none; } }
@keyframes siraj-m-fade { from { opacity: 0; } to { opacity: 1; } }
.m-animate { animation: siraj-m-enter var(--m-duration) var(--m-ease) both; animation-delay: calc(var(--m-i, 0) * var(--m-stagger)); }

/* Reduced motion: every level becomes an opacity-only change of ${SP.reducedMotion.duration}ms — no translate, scale, blur or camera */
@media (prefers-reduced-motion: reduce) {
  :root {${ORDER.map((n) => ` --siraj-m-${n}-duration: ${SP.reducedMotion.duration}ms; --siraj-m-${n}-exit: ${SP.reducedMotion.duration}ms; --siraj-m-${n}-stagger: 0ms; --siraj-m-${n}-translate: 0px; --siraj-m-${n}-scale: 1; --siraj-m-${n}-blur: 0px;`).join('')} }
  ${ALL} { transition-property: opacity !important; transition-timing-function: linear !important; }
  .m-enter, .m-exit, .m-line > span { transform: none !important; filter: none !important; }
  .m-reveal { clip-path: none !important; }
  .m-animate { animation-name: siraj-m-fade !important; animation-timing-function: linear !important; }
}
`;
fs.writeFileSync(path.join(OUTT, 'build/siraj-motion.css'), C);

// ---------------------------------------------------------------- TS
const TS = `// SIRAJ Motion Tokens v1.0 — GENERATED by tools/build-motion-system.js. Do not edit.
export const motionVersion = '1.0.0' as const;
export const easing = ${JSON.stringify(easing, null, 2)} as const;
export const levels = ${JSON.stringify(level, null, 2)} as const;
export const principles = ${JSON.stringify(SP.principles, null, 2)} as const;
export const transitions = ${JSON.stringify(tokens.transitions, null, 2)} as const;
export const components = ${JSON.stringify(components, null, 2)} as const;
export const reducedMotion = ${JSON.stringify(SP.reducedMotion, null, 2)} as const;
/** AIR / WIND: the force that moves silk, trees and plants (motion-system/tokens/siraj-wind.json). */
export const wind = ${JSON.stringify(wind, null, 2)} as const;
export type WindLevel = keyof typeof wind.levels;

export type MotionLevel = keyof typeof levels;
export type MotionEasing = keyof typeof easing;
export type MotionPrinciple = keyof typeof principles;
export type SignatureTransition = keyof typeof transitions;
export type MotionComponent = keyof typeof components;
export const motionLevels = ${JSON.stringify(ORDER)} as const satisfies readonly MotionLevel[];

/** CSS transition shorthand for a level, e.g. transition('hero', ['opacity', 'transform']). */
export function transition(level: MotionLevel, props: readonly string[] = ['opacity', 'transform', 'filter'], index = 0): string {
  const l = levels[level];
  const delay = index * l.stagger.ms;
  return props.map((p) => \`\${p} \${l.duration.ms}ms \${l.ease.css} \${delay}ms\`).join(', ');
}
/** Exit shorthand (release curve, the level's exit duration). */
export function exitTransition(level: MotionLevel, props: readonly string[] = ['opacity', 'transform']): string {
  const l = levels[level];
  return props.map((p) => \`\${p} \${l.exit.ms}ms \${l.exit.ease.css}\`).join(', ');
}
/** Respect prefers-reduced-motion: opacity only, ${SP.reducedMotion.duration}ms. */
export function prefersReducedMotion(): boolean {
  return typeof window !== 'undefined' && !!window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}
export function durationMs(level: MotionLevel): number {
  return prefersReducedMotion() ? reducedMotion.duration : levels[level].duration.ms;
}
`;
fs.writeFileSync(path.join(OUTT, 'build/siraj-motion.ts'), TS);

// ---------------------------------------------------------------- UMD for compositions
const UMD = `/* SIRAJ Motion Tokens v1.0 — GENERATED by tools/build-motion-system.js from motion-system/tokens. Do not edit. */\n(function(g){g.SIRAJ_MOTION_TOKENS=${JSON.stringify({ version: tokens.$version, order: ORDER, easing, level, transitions: tokens.transitions, components, reducedMotion: SP.reducedMotion, wind: { direction: WIND.direction, levels: WIND.levels, engine: windEngine, never: WIND.never } })};})(typeof window!=="undefined"?window:globalThis);\n`;
fs.writeFileSync(path.join(OUTT, 'build/siraj-motion.js'), UMD);
fs.writeFileSync(P('15-Motion-System/lib/siraj-motion-tokens.js'), UMD);

// ---------------------------------------------------------------- public data (the only brand data compositions may show)
const pub = {
  phone: CFG.contact.phone,
  phone_display: CFG.contact.phone_display,   // «7771 4404» — always shown in groups of four
  handle: CFG.contact.social_handle,          // shown with the Instagram icon, never «@»
  instagram_icon_svg: CFG.contact.social_icon_svg,
  company_ar: CFG.company.name_ar,
  project: { name_ar: CFG.founding_project.name_ar, city_ar: CFG.founding_project.location_ar, descriptor_ar: 'شقق سكنية ومحلات تجارية' },
};
if (!/^\d{8}$/.test(pub.phone)) throw new Error('contact.phone is not a confirmed 8-digit number: ' + pub.phone);
fs.writeFileSync(P('15-Motion-System/lib/siraj-public-data.js'), `/* SIRAJ public data for motion — GENERATED by tools/build-motion-system.js from 00-Brand-Foundation/brand.config.json.\n   Contains ONLY what may appear on screen: phone + Instagram icon/handle (never «@»), the project name «سراج», its city and its approved descriptor. */\n(function(g){g.SIRAJ_PUBLIC=${JSON.stringify(pub)};})(typeof window!=="undefined"?window:globalThis);\n`);

// ---------------------------------------------------------------- footage track (real ribbon position per frame)
// s = (x·W + (H−y)·H) / (W² + H²): 0 at the lower-start corner, 1 at the upper-end corner (frame diagonal).
// Mirrored footage (RTL) uses the same values in mirrored coordinates.
const track = {};
for (const [fmt, w, h] of [['16x9', 192, 108], ['9x16', 108, 192]]) {
  const src = P(`06-SIRAJ-Silk/Footage/SIRAJ_Silk_Ribbon-Pass_${fmt}_v1.0_alpha.webm`);
  const r = spawnSync('ffmpeg', ['-v', 'error', '-c:v', 'libvpx-vp9', '-i', src, '-vf', `alphaextract,scale=${w}:${h}`, '-f', 'rawvideo', '-pix_fmt', 'gray', '-'], { maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error('ffmpeg track failed: ' + r.stderr);
  const buf = r.stdout, n = Math.floor(buf.length / (w * h)), D2 = w * w + h * h;
  const rows = [];
  for (let f = 0; f < n; f++) {
    let mn = 2, mx = -1, cnt = 0;
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      if (buf[f * w * h + y * w + x] < 128) continue;
      const s = ((x + 0.5) * w + (h - y - 0.5) * h) / D2;
      if (s < mn) mn = s; if (s > mx) mx = s; cnt++;
    }
    rows.push(cnt ? [+mn.toFixed(4), +mx.toFixed(4)] : null);
  }
  track[fmt] = { fps: 24, frames: n, s: rows };
}
fs.writeFileSync(P('15-Motion-System/lib/siraj-footage-track.js'), `/* SIRAJ real-silk footage track — GENERATED by tools/build-motion-system.js (measured from the alpha of 06-SIRAJ-Silk/Footage).\n   For every frame (24 fps): [sMin, sMax] of the ribbon along the frame diagonal, s = (x·W + (H−y)·H)/(W²+H²),\n   0 = lower-start corner, 1 = upper-end corner. null = ribbon not in frame. Used to lock masks to the real silk. */\n(function(g){g.SIRAJ_FOOTAGE_TRACK=${JSON.stringify(track)};})(typeof window!=="undefined"?window:globalThis);\n`);

console.log('motion tokens v1.0 →', path.relative(ROOT, OUTT), '| public data | footage track', Object.keys(track).map((k) => `${k}:${track[k].frames}f`).join(' '));
