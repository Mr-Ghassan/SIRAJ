const SPRITE_NAMES = {
  siraj: ['building', 'property'], light: ['sun'], details: ['layers', 'floor-plan'],
  progress: ['construction', 'handover'], contact: ['call', 'whatsapp'],
};
FALLBACK.siraj = FALLBACK.projects; FALLBACK.light = FALLBACK.noor; FALLBACK.details = FALLBACK.harir; FALLBACK.progress = FALLBACK.updates;
function writeIcons() {
  const sprite = path.join(ROOT, '07-Icon-System', 'sprite', 'siraj-icons.svg');
  const src = fs.existsSync(sprite) ? fs.readFileSync(sprite, 'utf8') : '';
  const icons = {};
  const used = {};
  for (const [key, names] of Object.entries(SPRITE_NAMES)) {
    let found = null;
    for (const n of names) {
      const m = src.match(new RegExp(`<symbol[^>]*id="sj-${n}"[^>]*>([\\s\\S]*?)</symbol>`));
      if (m) { const vb = (m[0].match(/viewBox="([^"]+)"/) || [])[1] || '0 0 24 24'; found = { vb, body: m[1], from: `sprite #sj-${n}` }; break; }
    }
    icons[key] = found || { vb: '0 0 24 24', body: FALLBACK[key], from: 'built-in glyph' };
    used[key] = icons[key].from;
  }
  fs.writeFileSync(path.join(TPL, 'highlight-icons.js'), `// GENERATED by tools/build-social.js — highlight cover icons.\nwindow.SIRAJ_HIGHLIGHT_ICONS = ${JSON.stringify(icons, null, 2)};\n`);
  return used;
}

// ------------------------------------------------------------------ jobs
function readData(file) {
  const m = fs.readFileSync(file, 'utf8').match(/<script id="data" type="application\/json">([\s\S]*?)<\/script>/);
  return m ? JSON.parse(m[1]) : null;
}

function templateJobs() {
  const jobs = [];
  for (const f of fs.readdirSync(TPL).filter((x) => x.endsWith('.html')).sort()) {
    const d = readData(path.join(TPL, f));
    if (!d || !d.exports || !want(d.name)) continue;
    for (const [fmt, langs] of Object.entries(d.exports)) {
      for (const lang of langs) {
        const [w, h] = SIZE[fmt];
        const slides = fmt === 'carousel' ? d.slides.length : 1;
        for (let s = 1; s <= slides; s++) {
          const fname = fmt === 'carousel' ? `Carousel-${String(s).padStart(2, '0')}` : FNAME[fmt];
          jobs.push({ file: path.join(TPL, f), query: `format=${fmt}&lang=${lang}&slide=${s}`, w, h, out: path.join(OUT, `SIRAJ_Social_${d.name}_${fname}_${lang.toUpperCase()}_${V}.png`) });
          if (fmt === 'reel' && d.guide) jobs.push({ file: path.join(TPL, f), query: `format=${fmt}&lang=${lang}&guide=1`, w, h, out: path.join(OUT, `SIRAJ_Social_${d.name}_Reel-Guide_${lang.toUpperCase()}_${V}.png`) });
        }
      }
    }
  }
  return jobs;
}

async function renderJob(j) {
  const { page, cleanup } = await R.openPage({ file: `${j.file}?${j.query}`, width: j.w, height: j.h });
  await page.waitForSelector('body[data-ready="1"]', { timeout: 30000 });
  const qa = await page.evaluate(() => window.__qa || []);
  R.ensureDir(j.out);
  await page.screenshot({ path: j.out, clip: { x: 0, y: 0, width: j.w, height: j.h } });
  await cleanup();
  return qa;
}

async function pool(jobs, fn) {
  let i = 0;
  const problems = [];
  const worker = async () => {
    while (i < jobs.length) {
      const j = jobs[i++];
      const qa = await fn(j);
      const rel = path.relative(ROOT, j.out);
      if (qa && qa.length) problems.push(`${rel}\n    - ${qa.join('\n    - ')}`);
      process.stdout.write(`  ${qa && qa.length ? '!' : '✓'} ${rel}\n`);
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  return problems;
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  writeBrandData();
  const icons = writeIcons();
  let problems = [];

  const jobs = templateJobs();
  console.log(`Rendering ${jobs.length} template exports…`);
  problems = problems.concat(await pool(jobs, renderJob));

  // Highlight covers (1080 × 1920, icon inside the circular-safe centre)
  if (want('Highlight')) {
    const hl = Object.keys(icons).map((k) => ({ file: path.join(TPL, 'Highlight-Cover.html'), query: `icon=${k}`, w: 1080, h: 1920,
      out: path.join(SOC, 'Highlights', `SIRAJ_Social_Highlight_${k[0].toUpperCase() + k.slice(1)}_${V}.png`) }));
    hl.push({ file: path.join(TPL, 'Highlight-Cover.html'), query: 'sheet=1', w: 2160, h: 1240, out: path.join(SOC, 'Highlights', `SIRAJ_Social_Highlight-Set_Overview_${V}.png`) });
    console.log('Rendering highlight covers…');
    problems = problems.concat(await pool(hl, renderJob));
    console.log('  icons: ' + Object.entries(icons).map(([k, v]) => `${k}=${v}`).join(', '));
  }

  // Profile boards (avatar usage + 9-tile grid preview, built from the exports above)
  if (want('Profile')) {
    const pb = [
      { file: path.join(TPL, 'Profile-Avatar.html'), query: '', w: 1600, h: 1000, out: path.join(SOC, 'Profile', `SIRAJ_Social_Profile_Avatar-Usage_${V}.png`) },
      { file: path.join(TPL, 'Profile-Grid.html'), query: 'lang=ar', w: 1290, h: 3230, out: path.join(SOC, 'Profile', `SIRAJ_Social_Profile_Grid-Preview_AR_${V}.png`) },
    ];
    fs.mkdirSync(path.join(SOC, 'Profile'), { recursive: true });
    fs.copyFileSync(path.join(ROOT, '01-Logos', 'Dark', 'SIRAJ_Social-Avatar_Circle_v1.0.png'), path.join(SOC, 'Profile', `SIRAJ_Social_Avatar_Circle_1080_${V}.png`));
    console.log('Rendering profile boards…');
    problems = problems.concat(await pool(pb, renderJob));
  }

  if (problems.length) {
    console.log(`\nQA warnings (${problems.length}):\n  ` + problems.join('\n  '));
    process.exitCode = 1;
  } else console.log('\nAll exports passed layout QA.');
  // Chromium (SwiftShader) can stall on shutdown; don't let that keep the build alive.
  await Promise.race([R.close(), new Promise((r) => setTimeout(r, 5000))]);
  process.exit(process.exitCode || 0);
})().catch(async (e) => { console.error(e); await R.close(); process.exit(1); });
