// SIRAJ Social Media System — renders every template in 11-Social/Templates to PNG.
//   node tools/build-social.js                 # everything
//   node tools/build-social.js Quote Event     # only templates / boards whose name contains a filter
// Deterministic: all data comes from the template JSON blocks + 00-Brand-Foundation/brand.config.json.
const fs = require('fs');
const path = require('path');
const R = require('./lib/render');

const ROOT = R.ROOT;
const SOC = path.join(ROOT, '11-Social');
const TPL = path.join(SOC, 'Templates');
const OUT = path.join(SOC, 'Exports');
const V = 'v1.0';
const FILTER = process.argv.slice(2);
const want = (name) => !FILTER.length || FILTER.some((f) => name.toLowerCase().includes(f.toLowerCase()));

const SIZE = { post: [1080, 1350], carousel: [1080, 1350], square: [1080, 1080], story: [1080, 1920], reel: [1080, 1920], li: [1200, 627], x: [1600, 900] };
const FNAME = { post: 'Post', carousel: 'Carousel', square: 'Square', story: 'Story', reel: 'Reel', li: 'LinkedIn', x: 'X' };
const CONCURRENCY = 4;

// ------------------------------------------------------------------ generated data files
function writeBrandData() {
  const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, '00-Brand-Foundation', 'brand.config.json'), 'utf8'));
  // Post contact = phone + Instagram icon + handle (never «@», never the website). [ig] renders the Instagram glyph.
  const ct = cfg.contact;
  ct.phone_post = ct.phone_display;
  ct.post_line = `[[${ct.phone_display}]]  ·  [[[ig] ${ct.social_handle}]]`;   // phone in groups of four: «7771 4404»
  const js = `// GENERATED by tools/build-social.js from 00-Brand-Foundation/brand.config.json — do not edit by hand.\nwindow.SIRAJ_BRAND = ${JSON.stringify(cfg, null, 2)};\n`;
  fs.writeFileSync(path.join(TPL, 'brand-data.js'), js);
  return cfg;
}

